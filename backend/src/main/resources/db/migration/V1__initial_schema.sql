-- PostgreSQL schema for clean CampusConnect installations.
-- Existing databases managed by Hibernate must be backed up and migrated separately.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);
CREATE INDEX idx_users_email ON users(email);

CREATE TABLE clubs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    category VARCHAR(40) NOT NULL,
    logo_url VARCHAR(500),
    contact_email VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_clubs_name UNIQUE (name)
);
CREATE INDEX idx_clubs_name ON clubs(name);
CREATE INDEX idx_clubs_category ON clubs(category);
CREATE INDEX idx_clubs_active ON clubs(is_active);

CREATE TABLE club_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    club_id BIGINT NOT NULL REFERENCES clubs(id),
    role VARCHAR(30) NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_club_memberships_user_club UNIQUE (user_id, club_id)
);
CREATE INDEX idx_club_memberships_user ON club_memberships(user_id);
CREATE INDEX idx_club_memberships_club ON club_memberships(club_id);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(3000) NOT NULL,
    venue VARCHAR(250) NOT NULL,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    registration_deadline TIMESTAMPTZ NOT NULL,
    capacity INTEGER NOT NULL,
    registered_count INTEGER NOT NULL DEFAULT 0,
    banner_url VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    category VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    club_id BIGINT NOT NULL REFERENCES clubs(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    source_key VARCHAR(300),
    CONSTRAINT uk_events_source_key UNIQUE (source_key),
    CONSTRAINT ck_events_capacity CHECK (capacity >= 1),
    CONSTRAINT ck_events_registered_count CHECK (registered_count >= 0 AND registered_count <= capacity)
);
CREATE INDEX idx_events_club_id ON events(club_id);
CREATE INDEX idx_events_start_time ON events(start_time);
CREATE INDEX idx_events_status ON events(status);
CREATE INDEX idx_events_category ON events(category);
CREATE INDEX idx_events_active ON events(is_active);

CREATE TABLE event_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    event_id BIGINT NOT NULL REFERENCES events(id),
    registered_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_event_registration_user_event UNIQUE (user_id, event_id)
);
CREATE INDEX idx_event_registration_event ON event_registrations(event_id);
